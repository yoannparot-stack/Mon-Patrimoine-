// ImmOptima Firebase integration preflight (does not need credentials or network).
const fs=require('node:fs'),assert=require('node:assert/strict');
const workflow=fs.readFileSync('.github/workflows/build.yml','utf8');
const rules=fs.readFileSync('cloud/firestore.rules','utf8');
const guide=fs.readFileSync('cloud/DEPLOIEMENT.md','utf8');
const html=fs.readFileSync('index.html','utf8');
assert.match(workflow,/com\.immoptima\.app/,'Firebase preview must use new Android package');
assert.match(workflow,/IMMOPTIMA_KEYSTORE_BASE64/,'persistent signing required');
assert.match(rules,/request\.auth\.uid == userId/,'user isolation required');
assert.match(rules,/match \/users\/\{userId\}\/portfolios\/\{portfolioId\}/,'portfolio must be account scoped');
assert.match(rules,/portfolioId == 'current'/,'portfolio document ID must be constrained');
assert.match(rules,/allow create: if validWrite\(\) && request.resource.data.revision == 1/,'first cloud write starts at revision one');
assert.match(rules,/allow update: if validWrite\(\)/,'cloud update must use guarded validation');
assert.match(rules,/request.resource.data.revision == resource.data.revision \+ 1/,'cloud update must be sequential');
assert.doesNotMatch(rules,/resource == null/,'do not access missing resource on create');
assert.match(rules,/allow delete: if false;/,'client must not delete cloud portfolio');
assert.doesNotMatch(rules,/allow (?:read|write): if true/,'no public access');
assert.match(guide,/immoptima-6af3b/,'project ID documented');
assert.match(html,/IMMOPTIMA_ACCOUNT_STATUS='authentication_preview'/,'sign-in preview must remain explicit');
assert.match(html,/La synchronisation n’est pas encore active/,'do not pretend portfolio sync is ready');
assert.match(html,/backupDirectDrive\(\)/,'visible Drive backup must remain');
assert.match(html,/if\(immoptimaAuthState\.status==='signed_in'\)\{[\s\S]*?welcome\.remove\(\)/,'successful authentication must dismiss welcome overlay');
assert.match(html,/id="welcomeAccountInfo" style="[^"]*background:#171717;color:white/,'account button must use black primary style');
assert.match(html,/immoptima_pre_import_v1/,'pre-import rollback retained');
console.log('PASS: Firebase preflight, per-account rules and backward compatibility');
